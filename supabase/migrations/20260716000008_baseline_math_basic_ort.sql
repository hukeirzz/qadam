[asset:math_b9_theory_1]

Прямая и обратная пропорциональность

Прямая пропорциональность: y = kx. Одно растёт — другое растёт.
Обратная пропорциональность: y = k/x. Одно растёт — другое убывает.

Деление в данном отношении:
Разделить число C в отношении m:n → части C·m/(m+n) и C·n/(m+n).
Пример: 120 в отношении 1:3 → 30 и 90.

a/b=c/d → a·d=b·c  |  Прямая: y/x=const  |  Обратная: x·y=const$$),

