$$Отношение и пропорция

Отношение a к b = a/b (b≠0). Показывает, во сколько раз a больше b.
Пропорция: равенство двух отношений: a/b = c/d.
Основное свойство пропорции: произведение крайних = произведение средних.
a/b = c/d ⟺ a·d = b·c

