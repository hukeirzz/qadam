💡 Что нужно знать

Квадратный корень из числа a — это такое число, которое при умножении на само себя даёт a.
√25 = 5, потому что 5 · 5 = 25.

Важные правила для ОРТ:
• Под корнем √x никогда не может стоять отрицательное число.
• Корень из произведения можно разбить на два корня: √(a · b) = √a · √b. Это супер-приём для упрощения больших чисел!

🎯 Пример

Чему равен √144?

Ищем число, которое в квадрате даёт 144. Это 12, потому что 12 · 12 = 144.

Ответ: 12.

